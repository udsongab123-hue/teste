/* ========================================
   FORMATAR DATA
======================================== */

function formatarData(data) {

    return data.toLocaleDateString(
        "pt-BR",
        {
            weekday: "long",
            day: "numeric",
            month: "long",
            year: "numeric"
        }
    );
}


function chaveData(data) {

    const mes =
        String(
            data.getMonth() + 1
        ).padStart(2, "0");

    const dia =
        String(
            data.getDate()
        ).padStart(2, "0");

    return `${mes}-${dia}`;
}


/* ========================================
   MOSTRAR COMEMORAÇÕES
======================================== */

function mostrarComemoracoes(data) {

    const chave =
        chaveData(data);

    const lista =
        comemoracoes[chave] || [];

    tituloData.textContent =
        formatarData(data);

    contador.textContent =
        `${lista.length} ${
            lista.length === 1
                ? "data"
                : "datas"
        }`;

    cards.innerHTML = "";


    if (lista.length === 0) {

        cards.innerHTML = `

            <div class="sem-resultados">

                <div>📭</div>

                <h3>
                    Nenhuma comemoração cadastrada
                </h3>

                <p>
                    Ainda não temos uma data cadastrada
                    para este dia.
                </p>

            </div>

        `;

        return;
    }


    lista.forEach(
        (item, index) => {

            const card =
                document.createElement("article");

            card.className = "card";

            card.style.animationDelay =
                `${index * 0.1}s`;

            card.innerHTML = `

                <div class="card-topo">

                    <div class="card-emoji">
                        ${item.emoji}
                    </div>

                    <span
                        class="tipo ${item.tipo}"
                    >
                        ${item.tipo.toUpperCase()}
                    </span>

                </div>

                <h3>
                    ${item.nome}
                </h3>

                <p>
                    ${item.descricao}
                </p>

            `;

            cards.appendChild(card);

        }
    );
}


/* ========================================
   MOSTRAR DATA DE HOJE
======================================== */

function mostrarHoje() {

    const hoje =
        new Date();

    dataSelecionada =
        new Date(hoje);

    dataAtualElemento.textContent =
        formatarData(hoje);

    dataPesquisa.value =
        hoje.toISOString()
            .split("T")[0];

    mostrarComemoracoes(hoje);

    mesAtual =
        new Date(hoje);

    criarCalendario();
}


/* ========================================
   PESQUISA
======================================== */

buscarBtn.addEventListener(
    "click",
    () => {

        if (!dataPesquisa.value) {

            alert(
                "Escolha uma data primeiro!"
            );

            return;
        }

        const partes =
            dataPesquisa.value
                .split("-");

        const data =
            new Date(
                partes[0],
                partes[1] - 1,
                partes[2]
            );

        dataSelecionada =
            data;

        mostrarComemoracoes(data);

        mesAtual =
            new Date(data);

        criarCalendario();

    }
);


dataPesquisa.addEventListener(
    "change",
    () => {

        if (dataPesquisa.value) {

            buscarBtn.click();

        }

    }
);


hojeBtn.addEventListener(
    "click",
    mostrarHoje
);


/* ========================================
   CALENDÁRIO
======================================== */

function criarCalendario() {

    const ano =
        mesAtual.getFullYear();

    const mes =
        mesAtual.getMonth();


    const primeiroDia =
        new Date(
            ano,
            mes,
            1
        ).getDay();


    const ultimoDia =
        new Date(
            ano,
            mes + 1,
            0
        ).getDate();


    const nomesMeses = [

        "Janeiro",
        "Fevereiro",
        "Março",
        "Abril",
        "Maio",
        "Junho",
        "Julho",
        "Agosto",
        "Setembro",
        "Outubro",
        "Novembro",
        "Dezembro"

    ];


    mesAno.textContent =
        `${nomesMeses[mes]} ${ano}`;


    diasCalendario.innerHTML = "";


    /* Espaços antes do primeiro dia */

    for (
        let i = 0;
        i < primeiroDia;
        i++
    ) {

        const vazio =
            document.createElement("div");

        diasCalendario.appendChild(vazio);

    }


    /* Dias */

    for (
        let dia = 1;
        dia <= ultimoDia;
        dia++
    ) {

        const elemento =
            document.createElement("div");

        elemento.className =
            "dia";

        elemento.textContent =
            dia;


        const data =
            new Date(
                ano,
                mes,
                dia
            );


        const chave =
            chaveData(data);


        /* Verifica se é hoje */

        const hoje =
            new Date();

        if (

            dia === hoje.getDate() &&
            mes === hoje.getMonth() &&
            ano === hoje.getFullYear()

        ) {

            elemento.classList.add(
                "hoje"
            );

        }


        /* Verifica se possui comemoração */

        if (
            comemoracoes[chave]
        ) {

            elemento.classList.add(
                "tem-comemoracao"
            );

        }


        elemento.addEventListener(
            "click",
            () => {

                dataSelecionada =
                    data;

                dataPesquisa.value =
                    `${ano}-${
                        String(mes + 1)
                            .padStart(2, "0")
                    }-${
                        String(dia)
                            .padStart(2, "0")
                    }`;

                mostrarComemoracoes(data);

                window.scrollTo({
                    top: 0,
                    behavior: "smooth"
                });

            }
        );


        diasCalendario.appendChild(
            elemento
        );

    }

}


/* ========================================
   TROCAR MÊS
======================================== */

mesAnterior.addEventListener(
    "click",
    () => {

        mesAtual.setMonth(
            mesAtual.getMonth() - 1
        );

        criarCalendario();

    }
);


mesProximo.addEventListener(
    "click",
    () => {

        mesAtual.setMonth(
            mesAtual.getMonth() + 1
        );

        criarCalendario();

    }
);


/* ========================================
   MODO ESCURO
======================================== */

temaBtn.addEventListener(
    "click",
    () => {

        document.body.classList.toggle(
            "dark"
        );


        const escuro =
            document.body.classList.contains(
                "dark"
            );


        temaBtn.textContent =
            escuro
                ? "☀️"
                : "🌙";


        localStorage.setItem(
            "tema",
            escuro
                ? "dark"
                : "light"
        );

    }
);


/* Recuperar tema */

if (
    localStorage.getItem("tema")
    === "dark"
) {

    document.body.classList.add(
        "dark"
    );

    temaBtn.textContent =
        "☀️";
}


